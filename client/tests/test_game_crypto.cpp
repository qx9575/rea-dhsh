void test_s2c_real_frames_match_capture() {
    // Real non-chat s2c frames (numeric payloads) from .rea captures; the
    // embedded table must reproduce the reference decrypt byte for byte.
    check(sizeof(kS2cReal30a0Cipher) == sizeof(kS2cReal30a0Plain),
        "30a0 vector length mismatch");
    check(sizeof(kS2cReal3023Cipher) == sizeof(kS2cReal3023Plain),
        "3023 vector length mismatch");
    const dhsh::S2cTableCipher cipher(dhsh::s2cKeyTable());
    {
        auto payload = copy_of(kS2cReal30a0Cipher, sizeof(kS2cReal30a0Cipher));
        cipher.decryptInPlace(payload.data(), payload.size());
        expect_equal_bytes(payload.data(), kS2cReal30a0Plain, payload.size(),
            "real 0x30a0 frame mismatch");
    }
    {
        auto payload = copy_of(kS2cReal3023Cipher, sizeof(kS2cReal3023Cipher));
        cipher.decryptInPlace(payload.data(), payload.size());
        expect_equal_bytes(payload.data(), kS2cReal3023Plain, payload.size(),
            "real 0x3023 frame mismatch");
    }
}

